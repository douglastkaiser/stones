"""Generate all mark assets from stones.svg, without third-party dependencies.

The adaptive foreground puts the complete mark inside the central 66/108 circle.
Run before flutter_launcher_icons / flutter_native_splash. --check is CI's drift
guard and also asserts that generation has not replaced the custom web loader.
"""
import argparse
import json
from pathlib import Path
import struct
import zlib
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def asset_matches(path, content):
    if not path.exists():
        return False
    # Git's Windows checkout may use CRLF. Compare generated source as text,
    # while keeping exact byte validation for binary image assets.
    if path.suffix == '.dart':
        return path.read_text(encoding='utf-8') == content.decode('utf-8')
    return path.read_bytes() == content


def outputs():
    rects = [dict(node.attrib) for node in ET.parse(ROOT / 'assets/icon/stones.svg').getroot()]
    def png(size, dark=False, background=None, scale=1):
        data = bytearray()
        for y in range(size):
            data.append(0)
            for x in range(size):
                color = (*bytes.fromhex(background), 255) if background else (0, 0, 0, 0)
                for rect in rects:
                    left = (float(rect['x']) / 100 * scale + (1-scale)/2) * size
                    top = (float(rect['y']) / 100 * scale + (1-scale)/2) * size
                    width = float(rect['width']) / 100 * scale * size
                    height = float(rect['height']) / 100 * scale * size
                    coverage = max(0, min(x+1, left+width)-max(x, left)) * max(0, min(y+1, top+height)-max(y, top))
                    if coverage:
                        raw = rect['fill'][1:]
                        if dark:
                            raw = 'F0B782' if raw == '88401F' else 'F3E9D5'
                        rgb = bytes.fromhex(raw)
                        if background:
                            color = (*[round(rgb[i]*coverage+color[i]*(1-coverage)) for i in range(3)], 255)
                        else:
                            color = (*rgb, round(255*coverage))
                data.extend(color)
        def chunk(kind, payload):
            return struct.pack('!I', len(payload)) + kind + payload + struct.pack('!I', zlib.crc32(kind+payload))
        return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('!2I5B', size, size, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(data, 9)) + chunk(b'IEND', b'')

    result = {}
    for name, size, dark, bg, scale in [
        ('assets/icon/app_icon.png', 512, False, 'EDE5D7', 1),
        ('assets/icon/adaptive_foreground.png', 432, False, None, .66),
        ('assets/splash/mark.png', 288, False, None, 1),
        ('assets/splash/mark_dark.png', 288, True, None, 1),
        ('assets/splash/android12.png', 288, False, None, .70),
        ('assets/splash/android12_dark.png', 288, True, None, .70),
        ('web/favicon.png', 32, False, 'EDE5D7', 1),
        *[(f'web/icons/Icon-{s}.png', s, False, 'EDE5D7', 1) for s in (192, 512)],
        *[(f'web/icons/Icon-maskable-{s}.png', s, False, 'EDE5D7', .70) for s in (192, 512)],
    ]:
        result[name] = png(size, dark, bg, scale)
    # Flutter draws the same source geometry in theme colors, at any density.
    calls = '\n'.join(
        (f"  canvas.drawRect(const Rect.fromLTWH({r['x']}, {r['y']}, {r['width']}, {r['height']}), Paint()..color = accent);"
         if r['fill'] == '#88401F' else
         f"  canvas.drawRect(\n      const Rect.fromLTWH({r['x']}, {r['y']}, {r['width']}, {r['height']}), Paint()..color = foreground);")
        for r in rects)
    result['lib/widgets/stones_mark_geometry.dart'] = ("// Generated by scripts/generate_branding.py from assets/icon/stones.svg.\nimport 'package:flutter/material.dart';\n\nvoid paintStonesMark(Canvas canvas, Color foreground, Color accent) {\n" + calls + '\n}\n').encode()
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not asset_matches(path, content):
                raise SystemExit(f'Branding drift: run python scripts/generate_branding.py ({name})')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    index = (ROOT / 'web/index.html').read_text(encoding='utf-8')
    inline = ET.fromstring(index[index.index('<svg class='):index.index('</svg>')+6])
    source = ET.parse(ROOT / 'assets/icon/stones.svg').getroot()
    assert [tuple(n.get(k) for k in ('x', 'y', 'width', 'height')) for n in inline] == [tuple(n.get(k) for k in ('x', 'y', 'width', 'height')) for n in source], 'Web mark drift'
    assert 'id="stones-loader"' in index, 'Custom web loader was overwritten'
    assert 'web: false' in (ROOT / 'pubspec.yaml').read_text(), 'Native splash must not generate web HTML'
    manifest = json.loads((ROOT / 'web/manifest.json').read_text())
    assert manifest['scope'] == '.' and manifest['start_url'] == '.'
    print('Stones branding and custom loader verified')


if __name__ == '__main__':
    main()
